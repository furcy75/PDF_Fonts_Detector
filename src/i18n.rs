//! Système d'internationalisation (15 langues) + persistance des préférences utilisateur.

use std::path::PathBuf;

use serde::{Deserialize, Serialize};

#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum Language {
    En,
    Fr,
    Es,
    De,
    It,
    Pt,
    Nl,
    Pl,
    Sv,
    Da,
    Cs,
    Ro,
    Tr,
    Ru,
    Uk,
}

impl Language {
    pub const ALL: &'static [Language] = &[
        Language::En,
        Language::Fr,
        Language::Es,
        Language::De,
        Language::It,
        Language::Pt,
        Language::Nl,
        Language::Pl,
        Language::Sv,
        Language::Da,
        Language::Cs,
        Language::Ro,
        Language::Tr,
        Language::Ru,
        Language::Uk,
    ];

    pub fn code(self) -> &'static str {
        match self {
            Language::En => "en",
            Language::Fr => "fr",
            Language::Es => "es",
            Language::De => "de",
            Language::It => "it",
            Language::Pt => "pt",
            Language::Nl => "nl",
            Language::Pl => "pl",
            Language::Sv => "sv",
            Language::Da => "da",
            Language::Cs => "cs",
            Language::Ro => "ro",
            Language::Tr => "tr",
            Language::Ru => "ru",
            Language::Uk => "uk",
        }
    }

    pub fn native_name(self) -> &'static str {
        match self {
            Language::En => "English (EN)",
            Language::Fr => "Français (FR)",
            Language::Es => "Español (ES)",
            Language::De => "Deutsch (DE)",
            Language::It => "Italiano (IT)",
            Language::Pt => "Português (PT)",
            Language::Nl => "Nederlands (NL)",
            Language::Pl => "Polski (PL)",
            Language::Sv => "Svenska (SV)",
            Language::Da => "Dansk (DA)",
            Language::Cs => "Čeština (CS)",
            Language::Ro => "Română (RO)",
            Language::Tr => "Türkçe (TR)",
            Language::Ru => "Русский (RU)",
            Language::Uk => "Українська (UK)",
        }
    }

    pub fn from_locale_tag(tag: &str) -> Option<Self> {
        let prefix = tag
            .trim()
            .split(['-', '_', '.'])
            .next()
            .unwrap_or("")
            .to_ascii_lowercase();
        match prefix.as_str() {
            "en" => Some(Language::En),
            "fr" => Some(Language::Fr),
            "es" => Some(Language::Es),
            "de" => Some(Language::De),
            "it" => Some(Language::It),
            "pt" => Some(Language::Pt),
            "nl" => Some(Language::Nl),
            "pl" => Some(Language::Pl),
            "sv" => Some(Language::Sv),
            "da" => Some(Language::Da),
            "cs" => Some(Language::Cs),
            "ro" => Some(Language::Ro),
            "tr" => Some(Language::Tr),
            "ru" => Some(Language::Ru),
            "uk" => Some(Language::Uk),
            _ => None,
        }
    }

    /// Détecte automatiquement la langue du système d'exploitation (fallback: English).
    pub fn detect_system() -> Self {
        sys_locale::get_locale()
            .and_then(|tag| Self::from_locale_tag(&tag))
            .unwrap_or(Language::En)
    }

    pub fn strings(self) -> &'static Strings {
        match self {
            Language::En => &EN,
            Language::Fr => &FR,
            Language::Es => &ES,
            Language::De => &DE,
            Language::It => &IT,
            Language::Pt => &PT,
            Language::Nl => &NL,
            Language::Pl => &PL,
            Language::Sv => &SV,
            Language::Da => &DA,
            Language::Cs => &CS,
            Language::Ro => &RO,
            Language::Tr => &TR,
            Language::Ru => &RU,
            Language::Uk => &UK,
        }
    }
}

#[derive(Debug, Clone, Default, Serialize, Deserialize)]
pub struct AppSettings {
    pub language: Option<String>,
    pub download_dir: Option<PathBuf>,
}

impl AppSettings {
    fn config_path() -> Option<PathBuf> {
        dirs::config_dir().map(|d| d.join("pdf-fonts-detector").join("settings.json"))
    }

    pub fn load() -> Self {
        let Some(path) = Self::config_path() else {
            return Self::default();
        };
        std::fs::read_to_string(path)
            .ok()
            .and_then(|txt| serde_json::from_str(&txt).ok())
            .unwrap_or_default()
    }

    pub fn save(&self) {
        let Some(path) = Self::config_path() else {
            return;
        };
        if let Some(parent) = path.parent() {
            let _ = std::fs::create_dir_all(parent);
        }
        if let Ok(json) = serde_json::to_string_pretty(self) {
            let _ = std::fs::write(path, json);
        }
    }
}

