#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_locale_parsing_and_all_languages() {
        assert_eq!(Language::from_locale_tag("fr-FR"), Some(Language::Fr));
        assert_eq!(Language::from_locale_tag("en_US.UTF-8"), Some(Language::En));
        assert_eq!(Language::from_locale_tag("de-DE"), Some(Language::De));
        assert_eq!(Language::from_locale_tag("es-MX"), Some(Language::Es));
        assert_eq!(Language::from_locale_tag("pt_BR"), Some(Language::Pt));
        assert_eq!(Language::from_locale_tag("uk-UA"), Some(Language::Uk));
        assert_eq!(Language::from_locale_tag("xx-YY"), None);

        assert_eq!(Language::ALL.len(), 15);
        for &lang in Language::ALL {
            assert_eq!(Language::from_locale_tag(lang.code()), Some(lang));
            let s = lang.strings();
            assert!(!s.btn_open_pdf.is_empty());
            assert!(!s.btn_install_selected.is_empty());
            assert!(!s.status_ready.is_empty());
        }
    }
}
